import {
  ACCOUNT_TYPES,
  BILLING_METHODS,
  CLIENT_TYPES,
  COURT_TYPES,
  FILE_STATUSES,
  FILE_TEAM_ROLES,
  FILE_TYPES,
  JURISDICTIONS,
  OFFICE_LANGUAGES,
  PARTY_TYPES,
  PRIORITIES,
  REMINDER_STATUSES,
  ROLES,
  SESSION_OUTCOMES,
  DOCUMENT_LANGUAGES,
  DOCUMENT_STATUSES,
  DOCUMENT_TYPES,
  FOLDER_SYSTEM_KEYS,
  OCR_STATUSES,
  SESSION_TYPES,
  SUBSCRIPTION_STATUSES,
  TASK_STATUSES,
  AI_JOB_STATUSES,
  AI_SOURCE_TYPES,
} from '@nexlegtiq/shared-types';

import {
  AccountType,
  BillingMethod,
  ClientType,
  CourtType,
  FileStatus,
  FileTeamRole,
  FileType,
  Jurisdiction,
  OfficeLanguage,
  PartyType,
  Priority,
  ReminderStatus,
  Role,
  SessionOutcome,
  DocumentLanguage,
  DocumentStatus,
  DocumentType,
  FolderSystemKey,
  OcrStatus,
  SessionType,
  SubscriptionStatus,
  TaskStatus,
  AiJobStatus,
  AiSourceType,
} from '../generated/prisma/enums';

/** The enums in shared-types are hand-written copies of the Prisma enums used by the apps and contracts. */
describe('shared-types enums match the Prisma schema', () => {
  it.each([
    ['Jurisdiction', JURISDICTIONS, Jurisdiction],
    ['AccountType', ACCOUNT_TYPES, AccountType],
    ['OfficeLanguage', OFFICE_LANGUAGES, OfficeLanguage],
    ['Role', ROLES, Role],
    ['Priority', PRIORITIES, Priority],
    ['FileType', FILE_TYPES, FileType],
    ['FileStatus', FILE_STATUSES, FileStatus],
    ['ClientType', CLIENT_TYPES, ClientType],
    ['FileTeamRole', FILE_TEAM_ROLES, FileTeamRole],
    ['PartyType', PARTY_TYPES, PartyType],
    ['BillingMethod', BILLING_METHODS, BillingMethod],
    ['TaskStatus', TASK_STATUSES, TaskStatus],
    ['AiSourceType', AI_SOURCE_TYPES, AiSourceType],
    ['AiJobStatus', AI_JOB_STATUSES, AiJobStatus],
    ['SubscriptionStatus', SUBSCRIPTION_STATUSES, SubscriptionStatus],
    ['CourtType', COURT_TYPES, CourtType],
    ['SessionType', SESSION_TYPES, SessionType],
    ['SessionOutcome', SESSION_OUTCOMES, SessionOutcome],
    ['DocumentType', DOCUMENT_TYPES, DocumentType],
    ['DocumentStatus', DOCUMENT_STATUSES, DocumentStatus],
    ['OcrStatus', OCR_STATUSES, OcrStatus],
    ['DocumentLanguage', DOCUMENT_LANGUAGES, DocumentLanguage],
    ['FolderSystemKey', FOLDER_SYSTEM_KEYS, FolderSystemKey],
    ['ReminderStatus', REMINDER_STATUSES, ReminderStatus],
  ] as const)('%s', (_name, shared, prisma) => {
    expect([...shared].sort()).toEqual(Object.values(prisma).sort());
  });
});
